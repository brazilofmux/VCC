// Host-side gate: apps/journal/chacha.c against the RFC 8439 section
// 2.3.2 test vector. Build+run: tests/chacha.sh.
#include "../apps/journal/chacha.h"
#include <stdio.h>
#include <string.h>

int main(void)
{
    cc_u32 key[8], nonce[3];
    unsigned char out[64], i;
    static const unsigned char expect[64] = {
        0x10,0xf1,0xe7,0xe4,0xd1,0x3b,0x59,0x15,0x50,0x0f,0xdd,0x1f,0xa3,0x20,0x71,0xc4,
        0xc7,0xd1,0xf4,0xc7,0x33,0xc0,0x68,0x03,0x04,0x22,0xaa,0x9a,0xc3,0xd4,0x6c,0x4e,
        0xd2,0x82,0x64,0x46,0x07,0x9f,0xaa,0x09,0x14,0xc2,0xd7,0x05,0xd9,0x8b,0x02,0xa2,
        0xb5,0x12,0x9c,0xd1,0xde,0x16,0x4e,0xb9,0xcb,0xd0,0x83,0xe8,0xa2,0x50,0x3c,0x4e
    };
    for (i = 0; i < 8; ++i)
        key[i] = (cc_u32)(4*i) | ((cc_u32)(4*i+1) << 8) |
                 ((cc_u32)(4*i+2) << 16) | ((cc_u32)(4*i+3) << 24);
    nonce[0] = 0x09000000; nonce[1] = 0x4a000000; nonce[2] = 0x00000000;
    chacha20_block(key, 1, nonce, out);
    if (memcmp(out, expect, 64) != 0) { printf("chacha: FAIL\n"); return 1; }
    printf("chacha: PASS\n");
    return 0;
}
